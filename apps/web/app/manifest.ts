import type { MetadataRoute } from 'next';

/**
 * МАНИФЕСТЪТ — това, което превръща сайта в приложение на телефона.
 *
 * ═══ КАКВО ПРАВИ ═══
 *
 * Android чете точно този файл, когато някой избере „Добави на началния
 * екран". От него взима името, иконата, цвета на лентата и — най-важното —
 * `display: standalone`, което маха адресната лента. Без него ПРОБВАЙ се
 * отваря като страница в Chrome, с лента отгоре, и не изглежда като
 * приложение.
 *
 * ═══ ЗАЩО ДВЕ ИКОНИ 512 ═══
 *
 * `any` е иконата, каквато е. `maskable` е същата, но с поле по края, което
 * системата има право да отреже: Android реже с различна форма на всеки
 * телефон — кръг на един, капка на друг, заоблен квадрат на трети. Без
 * маскируем вариант крайчетата на логото се губят под маската.
 *
 * ═══ ЗАЩО `start_url` НЕ Е „/" ═══
 *
 * Всъщност е точно „/": началният екран е там и оттам човек има достъп до
 * всичко. Записано е изрично, защото по подразбиране браузърът взима
 * адреса, от който е добавено — а това може да е кой да е екран.
 *
 * ═══ iOS НЕ ЧЕТЕ ТОЗИ ФАЙЛ ЗА ИКОНАТА ═══
 *
 * Safari взима иконата от `<link rel="apple-touch-icon">`, който Next
 * генерира от `app/apple-icon.png`. Манифестът му служи само за
 * `display` и за името. Затова иконата се прави на две места — виж
 * `scripts/prepare-images.mjs`.
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    name: 'ПРОБВАЙ',
    short_name: 'ПРОБВАЙ',
    description: 'Виж как ти стои дрехата, преди да я поръчаш.',
    lang: 'bg',
    dir: 'ltr',

    start_url: '/',
    scope: '/',
    display: 'standalone',
    orientation: 'portrait',

    // Фонът се вижда за миг при отваряне, преди страницата да се нарисува.
    // Хартиеният цвят на приложението — иначе премигва бяло.
    background_color: '#faf6ef',
    // Лентата на състоянието. Хартиена, за да се слее с екрана — тъмна над
    // светло съдържание чете като чужда ивица, а не като част от
    // приложението.
    theme_color: '#faf6ef',

    categories: ['shopping', 'lifestyle'],

    icons: [
      { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      {
        src: '/icons/icon-512-maskable.png',
        sizes: '512x512',
        type: 'image/png',
        purpose: 'maskable',
      },
    ],
  };
}
