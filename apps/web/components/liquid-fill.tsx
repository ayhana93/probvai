/**
 * ЧАКАНЕТО: СНИМКАТА СЕ ПЪЛНИ
 *
 * Твоята снимка стои избледняла и в нея бавно се качва неоново зелено.
 * Долу от чертата снимката е в цвят, горе — сива. Пълненето Е лентата за
 * зареждане: няма отделна лента, няма въртящо кръгче.
 *
 * ═══ ЗАЩО ИМЕННО СНИМКАТА, А НЕ ЛЕНТА ═══
 *
 * Лентата под снимката казва „системата работи". Пълнещата се снимка казва
 * „НАД ТВОЯТА СНИМКА се работи" — а това е точно нещото, което човек чака.
 * И понеже се гледа веднъж на проба, а не по цял ден, движението тук е
 * оправдано: рядко видяното може да си позволи да е красиво.
 *
 * ═══ ЗАЩО НИВОТО НИКОГА НЕ СТИГА ДО ВЪРХА ═══
 *
 * Доставчикът не ни казва на колко процента е. Всяка лента, която пълзи до
 * 99% и там спира, е лъжа — и всеки я е разпознавал.
 *
 * Затова кривата тук се ЗАБАВЯ и се доближава до 92%, без да ги достига:
 * колкото по-дълго чака, толкова по-бавно се качва. Това е вярно твърдение
 * — „още работим, и вече е дълго". Пълни се до горе само в мига, в който
 * резултатът наистина е готов.
 *
 * ═══ ЗАЩО ВЪЛНАТА Е ДВЕ ═══
 *
 * Една вълна, която се движи, чете като лента с картинка. Две, с различна
 * скорост и прозрачност, се разминават непрекъснато и никога не повтарят
 * една и съща форма — оттам идва усещането за течност.
 */

'use client';

import * as React from 'react';
import { cn } from '@/lib/cn';

/** До колко процента се доближава нивото, без да ги стига. */
const CEILING = 92;

/**
 * Колко „бавно" се забавя кривата, в секунди. При 18 s нивото е около 58%
 * на 15-ата секунда и 74% на 30-ата — тоест по-голямата част от пътя минава
 * в първите половин минута, точно колкото трае обикновената проба.
 */
const TAU = 18;

function levelFor(elapsed: number, done: boolean): number {
  if (done) return 100;
  return CEILING * (1 - Math.exp(-elapsed / TAU));
}

export function LiquidFill({
  src,
  elapsed,
  done = false,
  className,
}: {
  /** Снимката на човека. Липсва ли — пълни се празно каре. */
  src: string | null;
  elapsed: number;
  done?: boolean;
  className?: string;
}) {
  const level = levelFor(elapsed, done);

  return (
    <div
      className={cn(
        'relative overflow-hidden rounded-[var(--radius-card)] bg-paper-3',
        className,
      )}
      role="progressbar"
      aria-valuemin={0}
      aria-valuemax={100}
      // Нарочно БЕЗ `aria-valuenow`: числото не е известно, а изговорено
      // число, което не значи нищо, е по-лошо от липсващо.
      aria-valuetext={`Правим пробата, ${elapsed} секунди`}
    >
      {/* ── Основата: снимката, извадена от цвят ─────────────────────────── */}
      {src ? (
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={src}
          alt=""
          draggable={false}
          className="size-full object-cover opacity-45 grayscale"
        />
      ) : (
        <div className="skeleton size-full" />
      )}

      {/* ── Течността: същата снимка, в цвят, отрязана до нивото ───────────
          `clip-path` се смята на графичния процесор и се прекъсва плавно —
          затова нивото може да се мени всяка секунда, без да подскача. */}
      <div
        className="absolute inset-0 transition-[clip-path] duration-[1100ms] ease-linear"
        style={{ clipPath: `inset(${100 - level}% 0 0 0)` }}
      >
        {src && (
          // eslint-disable-next-line @next/next/no-img-element
          <img src={src} alt="" draggable={false} className="size-full object-cover" />
        )}
        {/* Самото „оцветяване" на течността. `screen` вдига светлото към
            лайма, без да изяде лицето — обикновена плътна плоскост отгоре
            щеше да скрие снимката, а идеята е точно да се вижда. */}
        <div className="absolute inset-0 bg-lime opacity-55 mix-blend-screen" />
        <div className="absolute inset-0 bg-lime-deep opacity-20 mix-blend-multiply" />
      </div>

      {/* ── Повърхността ──────────────────────────────────────────────────
          Стои на нивото и се движи с него. Вълните са по-широки от карето,
          за да може да се плъзгат, без да се вижда край. */}
      <div
        className="pointer-events-none absolute inset-x-0 h-10 transition-[bottom] duration-[1100ms] ease-linear"
        style={{ bottom: `calc(${level}% - 20px)` }}
        aria-hidden="true"
      >
        {/* `left-0` без `right-0`: с двете едновременно широчината от 200%
            е свръхопределена и браузърът мълчаливо изхвърля едното. */}
        {/* Прозрачни са нарочно. При плътен лайм повърхността се чете като
            залепена лента върху снимката, а не като горния край на самата
            течност — през нея трябва да се вижда какво има отдолу. */}
        <Wave className="liquid-wave-a absolute bottom-0 left-0 h-10 w-[200%] text-lime opacity-[0.72]" />
        <Wave className="liquid-wave-b absolute bottom-[5px] left-0 h-10 w-[200%] text-lime opacity-30" />
      </div>
    </div>
  );
}

/**
 * ═══ ЗАЩО ШИРОЧИНАТА Е ТОЧНО 360, А НЕ „ДОСТАТЪЧНО" ═══
 *
 * Лентата се измества с половината от себе си и после започва отначало.
 * За да не се види скок в този миг, ПОЛОВИНАТА трябва да съдържа цял брой
 * вълни.
 *
 * Полувълната е широка 45 → вълната е 90. Осем полувълни правят 360, а
 * половината от тях (180) са точно две цели вълни. Първата ми стойност
 * беше 240 — там половината излиза 1⅓ вълни и на всяко завъртане линията
 * подскачаше.
 */
function Wave({ className }: { className?: string }) {
  return (
    <svg viewBox="0 0 360 40" preserveAspectRatio="none" className={className} fill="currentColor">
      <path
        d={
          'M0 18' +
          'c15-9 30-9 45 0s30 9 45 0s30-9 45 0s30 9 45 0' +
          's30-9 45 0s30 9 45 0s30-9 45 0s30 9 45 0' +
          'V40H0Z'
        }
      />
    </svg>
  );
}
