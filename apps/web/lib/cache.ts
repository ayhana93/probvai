/**
 * ПАМЕТ МЕЖДУ ЕКРАНИТЕ
 *
 * ═══ КАКЪВ ПРОБЛЕМ РЕШАВА ═══
 *
 * Всеки екран дърпаше данните си при всяко показване. Гардеробът, настройките
 * и балансът тръгваха от скелети всеки път, когато човек натисне нещо в
 * долното меню — макар че нищо не се е променило от преди пет секунди.
 *
 * Резултатът е приложение, което мига. Едно и също съдържание, показано и
 * скрито три пъти за минута, се усеща като бавно, дори всяка заявка да е
 * бърза.
 *
 * ═══ КАК РАБОТИ ═══
 *
 * Показаното веднъж се пази тук. Следващото показване го изкарва ВЕДНАГА и
 * чак тогава пита сървъра тихо, във фонов режим. Има ли промяна, екранът се
 * обновява без скелети; няма ли — не се е случило нищо видимо.
 *
 * ═══ ЗАЩО ОБИКНОВЕНА ПРОМЕНЛИВА, А НЕ ХРАНИЛИЩЕ НА БРАУЗЪРА ═══
 *
 * Паметта живее колкото раздела. „Назад" пази мястото; ново отваряне на
 * приложението започва наново. `localStorage` би пазил и след затваряне — а
 * тогава човек вижда вчерашния си баланс, докато мрежата се обади.
 *
 * ⚠ Тук НЕ влизат неща, които трябва да са верни в мига на показването —
 *   например резултатът от плащане. Те се четат винаги от сървъра.
 */

const store = new Map<string, unknown>();

export function readCache<T>(key: string): T | undefined {
  return store.get(key) as T | undefined;
}

export function writeCache<T>(key: string, value: T): void {
  store.set(key, value);
}

/**
 * Изхвърля всичко, чийто ключ започва с даден низ.
 *
 * Ползва се, когато едно действие на един екран прави данните на друг
 * неверни — публикуване в Lookbook от гардероба например.
 */
export function dropCache(prefix: string): void {
  for (const key of store.keys()) {
    if (key.startsWith(prefix)) store.delete(key);
  }
}
