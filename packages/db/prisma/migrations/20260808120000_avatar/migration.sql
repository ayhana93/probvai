-- Профилната снимка е ОТДЕЛНА от снимката за проба.
--
-- Двете имат различни изисквания и се сменят по различен повод: профилната е
-- лице отблизо и стои с месеци, снимката за проба е цял ръст и се сменя при
-- всяко качване. Една колона за двете значи, че селфи в кръгчето мълчаливо
-- става снимката, върху която пробваме дрехи.

ALTER TABLE "users" ADD COLUMN "avatar_key" TEXT;

-- Правото за писане се дава изрично, колона по колона — както при всички
-- останали. Без този ред `app_user` вижда полето, но не може да го смени, и
-- качването на профилна снимка би падало с „permission denied for table
-- users" чак по време на работа.
GRANT UPDATE (avatar_key) ON TABLE public.users TO app_user;
