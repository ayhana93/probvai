-- ============================================================================
-- БАЛАНСЪТ НЕ СЛИЗА ПОД НУЛАТА — този път го казва самата база
-- ============================================================================
--
-- Дотук отрицателен баланс беше невъзможен по три причини, всичките в кода:
-- `SELECT ... FOR UPDATE` на реда, отказ при `credits < 1`, и частичен
-- уникален индекс `credit_ledger_ref_once`, който спира второто начисляване
-- за една и съща Stripe сесия.
--
-- Три причини в кода са три места, където един ден някой ще напише четвърто
-- обръщение към `users.credits` и няма да мине през нито едно от тях. Ето
-- защо тук идва пояс, който не зависи от това кой го е извикал: правило на
-- самата таблица.
--
-- ═══ КАКВО ПРАВИ ═══
--
-- Всяка заявка, която би оставила отрицателен баланс, се проваля НА МЯСТО и
-- връща цялата транзакция назад. Не остава половин операция — леджерът и
-- балансът или се променят заедно, или не се променя нищо.
--
-- ═══ ЗАЩО НЕ Е `NOT VALID` ═══
--
-- `NOT VALID` пази само новите редове и не поглежда старите. Тук искаме точно
-- обратното: ако в базата ВЕЧЕ има отрицателен баланс, тази миграция трябва да
-- се провали шумно, а пускането да спре. Отрицателен баланс значи, че някъде
-- изтичат генерации; това е новина, която трябва да се научи веднага, а не да
-- се маскира от миграция, минала успешно.

ALTER TABLE public.users
  ADD CONSTRAINT users_credits_non_negative CHECK (credits >= 0);

-- Балансът, записан в леджера, е снимка на `users.credits` след операцията.
-- Щом единият не може да е отрицателен, другият също не може — иначе двата
-- реда разказват различни истории за един и същ миг.
ALTER TABLE public.credit_ledger
  ADD CONSTRAINT credit_ledger_balance_non_negative CHECK (balance >= 0);
