/**
 * ТАЙНИТЕ ВЪПРОСИ
 *
 * ═══ ЗАЩО СЕ ПАЗИ КЛЮЧ, А НЕ ТЕКСТ ═══
 *
 * В базата влиза `pet`, не „Как се казваше първият ти домашен любимец?".
 * Текстът може да се преформулира или преведе; ключът остава. Иначе всяка
 * поправка на изречение би обезсилила отговорите на всички, които са го
 * избрали.
 *
 * ═══ КАК СА ИЗБРАНИ ═══
 *
 * Всеки въпрос трябва да има отговор, който е:
 *   • един и същ след пет години — затова няма „коя е любимата ти песен";
 *   • кратък и една дума — дълъг отговор се помни грешно;
 *   • труден за намиране в социална мрежа — затова няма „как се казва
 *     майка ти" и „в кой град си роден".
 *
 * Последното не е дребно. Таен въпрос, чийто отговор стои в публичен
 * профил, не е защита, а списък с указания.
 */

export type SecurityQuestion = {
  key: string;
  text: string;
};

export const SECURITY_QUESTIONS: SecurityQuestion[] = [
  { key: 'pet', text: 'Как се казваше първият ти домашен любимец?' },
  { key: 'street', text: 'На коя улица живееше като дете?' },
  { key: 'teacher', text: 'Как се казваше любимият ти учител?' },
  { key: 'dish', text: 'Кое ястие ти правеше баба ти най-често?' },
  { key: 'toy', text: 'Коя беше любимата ти играчка като дете?' },
  { key: 'nickname', text: 'Как те наричаха приятелите ти в училище?' },
];

const BY_KEY = new Map(SECURITY_QUESTIONS.map((question) => [question.key, question]));

export function isSecurityQuestion(value: unknown): value is string {
  return typeof value === 'string' && BY_KEY.has(value);
}

export function questionText(key: string): string | null {
  return BY_KEY.get(key)?.text ?? null;
}

/**
 * Въпрос за непознат имейл.
 *
 * ═══ ЗАЩО ИЗОБЩО ВРЪЩАМЕ ВЪПРОС ЗА НЕСЪЩЕСТВУВАЩ АКАУНТ ═══
 *
 * Екранът за забравена парола показва тайния въпрос на човека. Ако за
 * непознат имейл отговаряхме „няма такъв профил", всеки щеше да може да
 * проверява кой има акаунт при нас — с един списък имейли и малко търпение.
 *
 * Затова отговорът изглежда еднакво и в двата случая: показва се въпрос.
 * За непознат имейл той се избира по хеш на самия имейл, тоест е един и същ
 * при всяко питане — променлив въпрос би издал измамата веднага.
 *
 * Отговорът после не съвпада с нищо и се вижда обичайното „грешен отговор".
 */
export function decoyQuestionFor(email: string): SecurityQuestion {
  let sum = 0;
  const normalized = email.trim().toLowerCase();
  for (let i = 0; i < normalized.length; i += 1) {
    sum = (sum * 31 + normalized.charCodeAt(i)) % 100_000;
  }
  return SECURITY_QUESTIONS[sum % SECURITY_QUESTIONS.length]!;
}
